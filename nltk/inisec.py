"""
Early security module to prevent module hijacking from the current working directory.

This module installs a custom `MetaPathFinder` that intercepts imports of modules
that NLTK or its dependencies might use, and blocks them if they resolve to the
current working directory.

The list of protected modules was generated by grepping the entire NLTK codebase
for import statements and includes:
- All third-party dependencies (e.g., numpy, joblib, scikit-learn, gensim, etc.)
- All standard library modules used anywhere in NLTK
- NLTK itself

Additionally, any import originating from NLTK code is intercepted via caller
detection, providing an extra layer of protection even for modules not explicitly
listed (e.g., future imports).

The hook is installed at the very top of `nltk/__init__.py` to ensure it is active
before any NLTK code executes.
"""

import importlib.abc
import importlib.machinery
import os
import sys
from pathlib import Path


class NLTKSafeImportFinder(importlib.abc.MetaPathFinder):
    """
    Custom finder that blocks imports of vulnerable modules from the CWD.
    """

    # Exhaustive list of all top-level modules NLTK or its dependencies import,
    # generated from a comprehensive grep of the codebase.
    _vulnerable_modules = frozenset(
        (
            # ---- Third-party packages (direct and optional dependencies) ----
            "numpy",
            "numpypy",
            "joblib",
            "tqdm",
            "scipy",
            "sklearn",
            "scikit_learn",
            "matplotlib",
            "pandas",
            "requests",
            "twython",
            "regex",
            "click",
            "pytest",
            "defusedxml",
            "gensim",
            "python_crfsuite",
            "pycrfsuite",
            "beautifulsoup4",
            "lxml",
            "dateutil",
            "python_dateutil",
            # ---- Standard library modules (all found in the grep) ----
            # Core builtins and system
            "abc",
            "argparse",
            "array",
            "ast",
            "base64",
            "bisect",
            "builtins",
            "codecs",
            "collections",
            "contextlib",
            "copy",
            "csv",
            "dataclasses",
            "datetime",
            "doctest",
            "email",
            "enum",
            "fnmatch",
            "fractions",
            "functools",
            "gc",
            "getopt",
            "glob",
            "gzip",
            "hashlib",
            "hmac",
            "html",
            "http",
            "importlib",
            "inspect",
            "io",
            "ipaddress",
            "itertools",
            "json",
            "locale",
            "logging",
            "math",
            "multiprocessing",
            "ntpath",
            "operator",
            "os",
            "pathlib",
            "pickle",
            "platform",
            "pprint",
            "queue",
            "random",
            "re",
            "secrets",
            "shelve",
            "shutil",
            "socket",
            "sqlite3",
            "ssl",
            "stat",
            "string",
            "subprocess",
            "sys",
            "tempfile",
            "textwrap",
            "threading",
            "time",
            "timeit",
            "tkinter",
            "traceback",
            "types",
            "typing",
            "unicodedata",
            "unittest",
            "urllib",
            "uuid",
            "warnings",
            "weakref",
            "webbrowser",
            "xml",
            "zipfile",
            # ---- NLTK itself (to catch attempts to shadow it, though limited) ----
            "nltk",
        )
    )

    def __init__(self):
        # Cache the resolved CWD once at startup to avoid repeated disk access
        try:
            self._cwd = Path.cwd().resolve()
        except FileNotFoundError:
            self._cwd = None

    def _is_import_from_nltk(self):
        """
        Walk the call stack to determine if the import originated from NLTK code.
        Skips importlib internals and the hook's own module.
        """
        frame = sys._getframe(1)
        while frame:
            module_name = frame.f_globals.get("__name__")
            # Skip importlib, frozen importlib, and the hook's own module
            if (
                module_name
                and not module_name.startswith(("importlib.", "_frozen_importlib"))
                and module_name != "nltk.inisec"
            ):
                return module_name.startswith("nltk")
            frame = frame.f_back
        return False

    def find_spec(self, fullname, path, target=None):
        top_level = fullname.split(".")[0]

        # Check if the module is in our explicit vulnerable list
        if top_level not in self._vulnerable_modules:
            # If not in the list, we still intercept if the import originates from NLTK
            if not self._is_import_from_nltk():
                return None
            # If it is from NLTK, we continue to the path check below

        # Use PathFinder directly to avoid recursion
        spec = importlib.machinery.PathFinder.find_spec(fullname, path, target)
        if spec is None:
            return None

        if self._cwd is None:
            # CWD was deleted; we can't determine safety, allow import
            return spec

        # Check if the module resolves to the CWD (file, package, or namespace package)
        try:
            # For regular modules/packages with an origin file
            if spec.origin:
                module_path = Path(spec.origin).resolve()
                if module_path.parent == self._cwd:
                    raise ImportError(
                        f"Blocked import of {fullname} from current working directory "
                        "for security reasons. Use '-P' or set PYTHONSAFEPATH to prevent "
                        "Python from searching the current working directory."
                    )

            # For namespace packages (origin is None, but we have search locations)
            if spec.submodule_search_locations:
                for loc in spec.submodule_search_locations:
                    pkg_dir = Path(loc).resolve()
                    if pkg_dir.parent == self._cwd:
                        raise ImportError(
                            f"Blocked import of {fullname} from current working directory "
                            "for security reasons. Use '-P' or set PYTHONSAFEPATH to prevent "
                            "Python from searching the current working directory."
                        )

        except FileNotFoundError:
            # Something went wrong reading the path; allow import
            pass

        return spec


# Install the finder only once, unless disabled via environment variable
if not os.environ.get("NLTK_DISABLE_IMPORT_SECURITY"):
    if not any(isinstance(f, NLTKSafeImportFinder) for f in sys.meta_path):
        sys.meta_path.insert(0, NLTKSafeImportFinder())
